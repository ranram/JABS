import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const rosterSources = {
  'street-fighter-6': 'sf6.md',
  'tekken-8': 'tekken8.md',
  'avatar-legends': 'avatar-legends.md',
  'marvel-tokon': 'marvel-tokon.md',
  'guilty-gear-strive': 'guilty-gear-strive.md',
  '2xko': '2xko.md',
  'blazblue-centralfiction': 'blazblue-centralfiction.md',
  'fatal-fury-city-of-the-wolves': 'ff-cotw.md',
  'granblue-fantasy-versus-rising': 'granblue-versus-rising.md',
  'king-of-fighters-xv': 'kof-xv.md',
  'melty-blood-type-lumina': 'melty-blood-twi-lumina.md',
  'mortal-kombat-1': 'mortal-kombat-1.md',
  'ultimate-marvel-vs-capcom-3': 'umvc3.md',
  'super-smash-bros-ultimate': 'ultimate.md',
  'under-night-in-birth-ii-sys-celes': 'under-night-in-birth-sysceles.md'
};

const root = process.cwd();
const outputPath = resolve(root, 'src/shared/generatedCharacterRosters.ts');
const nativeOutputPath = resolve(root, 'src-tauri/resources/character_rosters.json');
const rosters = {};

for (const [gameId, source] of Object.entries(rosterSources)) {
  const text = await readFile(resolve(root, 'character-lists', source), 'utf8');
  const seen = new Set();
  const characters = [];

  for (const rawLine of text.split(/\r?\n/u)) {
    const character = rawLine.trim();
    const identity = character.toLocaleLowerCase('en-US');
    if (!character || seen.has(identity)) continue;
    seen.add(identity);
    characters.push(character);
  }

  if (characters.length === 0) {
    throw new Error(`Character roster ${source} is empty.`);
  }
  rosters[gameId] = characters;
}

const generated = `// Generated by scripts/sync-character-rosters.mjs from reviewed files in character-lists/.\n` +
  `// Do not edit this file directly. Run pnpm run rosters:sync after updating a source list.\n` +
  `export const generatedCharacterRosters = ${JSON.stringify(rosters, null, 2)} as const;\n`;
const nativeGenerated = `${JSON.stringify(rosters, null, 2)}\n`;

if (process.argv.includes('--check')) {
  const current = await readFile(outputPath, 'utf8').catch(() => '');
  const nativeCurrent = await readFile(nativeOutputPath, 'utf8').catch(() => '');
  if (current !== generated || nativeCurrent !== nativeGenerated) {
    throw new Error('Generated character rosters are stale. Run pnpm run rosters:sync and review the diff.');
  }
} else {
  await mkdir(resolve(root, 'src-tauri/resources'), { recursive: true });
  await writeFile(outputPath, generated, 'utf8');
  await writeFile(nativeOutputPath, nativeGenerated, 'utf8');
}
