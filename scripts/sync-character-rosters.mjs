import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { validateCharacterCatalog } from './character-catalog.mjs';

const gameIds = [
  "street-fighter-6",
  "tekken-8",
  "avatar-legends",
  "marvel-tokon",
  "guilty-gear-strive",
  "2xko",
  "blazblue-centralfiction",
  "fatal-fury-city-of-the-wolves",
  "granblue-fantasy-versus-rising",
  "king-of-fighters-xv",
  "melty-blood-type-lumina",
  "mortal-kombat-1",
  "ultimate-marvel-vs-capcom-3",
  "super-smash-bros-ultimate",
  "under-night-in-birth-ii-sys-celes"
];
const root = process.cwd();
const rosters = {};
const aliases = {};
for (const gameId of gameIds) {
  const source = `character-lists/${gameId}.json`;
  const catalog = JSON.parse(await readFile(resolve(root, source), 'utf8'));
  const validated = validateCharacterCatalog(catalog, source);
  rosters[gameId] = validated.names;
  aliases[gameId] = validated.aliases;
}

const header = '// Generated by scripts/sync-character-rosters.mjs from reviewed files in character-lists/.\n'
  + '// Do not edit this file directly. Run pnpm run rosters:sync after updating a source list.\n';
const outputs = {
  'src/shared/generatedCharacterRosters.ts': `${header}export const generatedCharacterRosters = ${JSON.stringify(rosters, null, 2)} as const;\n`,
  'src/shared/generatedCharacterAliases.ts': `${header}export const generatedCharacterAliases: Readonly<Record<string, Readonly<Record<string, string>>>> = ${JSON.stringify(aliases, null, 2)};\n`,
  'src-tauri/resources/character_rosters.json': `${JSON.stringify(rosters, null, 2)}\n`,
  'src-tauri/resources/character_aliases.json': `${JSON.stringify(aliases, null, 2)}\n`
};
for (const [file, generated] of Object.entries(outputs)) {
  const path = resolve(root, file);
  if (process.argv.includes('--check')) {
    const current = await readFile(path, 'utf8').catch(() => '');
    if (current !== generated) throw new Error(`${file} is stale. Run pnpm run rosters:sync and review the diff.`);
  } else {
    await mkdir(resolve(root, 'src-tauri/resources'), { recursive: true });
    await writeFile(path, generated, 'utf8');
  }
}
